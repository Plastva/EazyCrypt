function getTranslation(key) {
  const lang = localStorage.getItem("language") || "ro";
  return translations[lang]?.[key] || translations.ro[key] || key;
}

window.getTranslation = getTranslation;

function setLanguage(lang) {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    const text = translations[lang]?.[key] || translations.ro[key] || key;

    element.textContent = text;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-i18n-placeholder");
    const text = translations[lang]?.[key] || translations.ro[key] || key;

    element.placeholder = text;
  });

  localStorage.setItem("language", lang);
  window.dispatchEvent(new CustomEvent("languageChanged"));
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLanguage = localStorage.getItem("language") || "ro";
  const select = document.getElementById("languageSelect");

  if (select) {
    select.value = savedLanguage;

    select.addEventListener("change", () => {
      setLanguage(select.value);
    });
  }

  setLanguage(savedLanguage);
});
